import json,os,pathlib,re,subprocess,tempfile,unittest
ROOT=pathlib.Path(__file__).resolve().parents[1]
SERVER=(ROOT/'deploy/community-preview/server.py').read_text()
NGINX=(ROOT/'deploy/community-preview/nginx.conf').read_text()
DEPLOY=(ROOT/'deploy/community-preview/deploy.sh').read_text()
WORKFLOW=(ROOT/'.github/workflows/community-preview-deploy.yml').read_text()
README=(ROOT/'deploy/community-preview/README.md').read_text()
CONNECTION=(ROOT/'deploy/community-preview/connection.json').read_text()
MINI=(ROOT/'deploy/community-preview/prepare-mini.cjs').read_text()
WORKBENCH=(ROOT/'demos/community-stage/workbench.js').read_text()
PORTAL=(ROOT/'demos/community-stage/communities.js').read_text()
class PreviewCandidateContract(unittest.TestCase):
 def test_dedicated_host_and_cookie_do_not_claim_shared_routes(self):
  self.assertIn('community-preview.wenwenwenyiyiyi.work',NGINX)
  self.assertNotIn('server_name wenwenwenyiyiyi.work;',NGINX)
  self.assertIn('__Host-xj_community_preview',SERVER)
  self.assertIn('PRODUCTION_COOKIE_DENIED',SERVER)
  self.assertNotIn("Set-Cookie','__Host-xj_customer=",SERVER)
  self.assertIn("target+'#preview='",SERVER)
  self.assertIn("location.hostname==='community-preview.wenwenwenyiyiyi.work'",WORKBENCH)
  self.assertIn("location.hostname==='community-preview.wenwenwenyiyiyi.work'",PORTAL)
 def test_nginx_overwrites_private_origin_header(self):
  self.assertRegex(NGINX,r'proxy_set_header X-Xuanjun-Client-IP "";\s*proxy_set_header X-Xuanjun-Client-IP \$remote_addr;')
  self.assertIn('TrustedNginxSource',SERVER)
 def test_candidate_workflow_has_no_deploy_job_or_automatic_push(self):
  self.assertIn('workflow_dispatch:',WORKFLOW)
  self.assertNotRegex(WORKFLOW,r'(?m)^\s*push:')
  self.assertNotRegex(WORKFLOW,r'(?m)^\s*deploy:')
  for forbidden in ('systemctl','nginx -t','sudo -n','/etc/nginx'):self.assertNotIn(forbidden,WORKFLOW)
 def test_scope_discloses_mock_login_and_disabled_money(self):
  for phrase in ('test Mock','payments are disabled','Finance remains UNCONFIRMED','not real wx.login/code2session'):self.assertIn(phrase,README)
 def test_deploy_candidate_is_valid_bash(self):
  p=subprocess.run(['bash','-n',str(ROOT/'deploy/community-preview/deploy.sh')],cwd=ROOT,text=True,capture_output=True,timeout=10)
  self.assertEqual(p.returncode,0,p.stdout+p.stderr)
 def test_rollback_covers_external_checks_and_old_objects(self):
  for token in ('current.symlink','$BACKUP/unit','$BACKUP/nginx','$BACKUP/enabled','$BACKUP/active'):self.assertIn(token,DEPLOY)
  trap=DEPLOY.index("trap 'rc=$?; if rollback; then exit 90; else exit 91; fi' ERR")
  public=DEPLOY.index('curl_cmd --fail --silent --show-error --max-time 10 "https://$HOST/community/health"')
  clear=DEPLOY.index('trap - ERR')
  self.assertLess(trap,public);self.assertLess(public,clear)
  self.assertIn('rm -rf --one-file-system "$RELEASE"',DEPLOY)
  self.assertIn('ROLLBACK_HOLD',DEPLOY)
  self.assertIn('$TX/HOLD',DEPLOY)
  self.assertIn('if rollback; then exit 90; else exit 91; fi',DEPLOY)
  self.assertNotIn('echo ROLLBACK_COMPLETE\n}',DEPLOY)
 def test_connected_mini_candidate_is_exact_and_non_mutating(self):
  self.assertIn("require('./endpoint.cjs')",MINI)
  self.assertEqual(json.loads((ROOT/'deploy/community-preview/endpoint-profiles.json').read_text())['legacy'],'https://community-preview.wenwenwenyiyiyi.work')
  self.assertIn("request_domain_change_performed:false",MINI)
  self.assertIn("upload_performed:false",MINI)
  self.assertIn('"real_wechat_login_verified": false',CONNECTION)
  self.assertIn('"request_domain_required": "https://community-preview.wenwenwenyiyiyi.work"',CONNECTION)
  with tempfile.TemporaryDirectory() as tmp:
   out=pathlib.Path(tmp)/'connected-mini'
   env=dict(os.environ,COMMUNITY_CONNECTED_MINI_OUTPUT=str(out))
   p=subprocess.run(['node',str(ROOT/'deploy/community-preview/prepare-mini.cjs')],cwd=ROOT,env=env,text=True,capture_output=True,timeout=30)
   self.assertEqual(p.returncode,0,p.stdout+p.stderr)
   app=(out/'app.js').read_text()
   receipt=json.loads((out/'CONNECTED_PREVIEW_RECEIPT.json').read_text())
   self.assertRegex(app,r"baseUrl:\s*'https://community-preview\.wenwenwenyiyiyi\.work'")
   self.assertIn("payments: false",app)
   self.assertIn("commerce: true",app)
   self.assertEqual(receipt['baseUrl'],'https://community-preview.wenwenwenyiyiyi.work')
   self.assertTrue(receipt['commerce']);self.assertFalse(receipt['payments'])
   self.assertFalse(receipt['request_domain_change_performed'])
   self.assertFalse(receipt['upload_performed'])
   self.assertFalse(receipt['real_wechat_login_verified'])
if __name__=='__main__':unittest.main()
